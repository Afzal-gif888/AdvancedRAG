        q("direct", f"How heavy is the {n}?", [{"file": f, "phrases": [f"{p['weight']} grams"]}], split=split, fact=f"{n}-weight")
        q("direct", f"How long is the warranty on the {n}?", [{"file": f, "phrases": [n, f"{p['warranty']} months"]}], split=split, fact=f"{n}-warranty")
        q("keyword", f"{n} battery months", [{"file": f, "phrases": [f"{p['battery']} months"]}], split=split, fact=f"{n}-battery")
