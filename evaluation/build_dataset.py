def build_policy_pdf() -> bytes:
    """A text PDF whose security paragraph is split across a page break."""
    from reportlab.pdfgen import canvas

    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=(612, 792))

    def page(lines):
        y = 740
        for ln in lines:
            c.setFont("Helvetica", 11)
            c.drawString(60, y, ln)
            y -= 16
        c.showPage()

    page(["Facilities policy", "", "Visitors must wear a badge at all times in the building.", "Parking permits are issued by the facilities desk.",
          "The visitor Wi-Fi password changes every Monday morning."])
