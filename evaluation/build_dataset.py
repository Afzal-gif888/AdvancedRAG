"""Builds the retrieval evaluation dataset: a synthetic corpus and labelled questions.

    python evaluation/build_dataset.py            # writes evaluation/dataset/** (deterministic, seed below)

Why synthetic: the data contains no private or licensed text, the ground truth is known by construction (every
question is generated from a fact table, and its relevance label is "this file and these exact phrases"), and the
corpus can be regenerated byte for byte.

Labels are CONTENT based (file + required phrases), not chunk ids, so the same questions can be scored against any
chunking strategy. A question has a list of evidence items; a retrieved chunk is relevant if it satisfies any item.

Splits: facts are assigned to `dev` or `test` alternately. The code in this repository was not tuned on either
split (see evaluation/README.md); the split exists so that nobody tunes on the test set later.
"""
