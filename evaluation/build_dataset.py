    # keyword-style and misspelled variants of the same facts
    for n, (section, key, tmpl, value, variants) in enumerate(HANDBOOK):
        kw, typo = KEYWORD_VARIANTS[key]
        split = "dev" if n % 2 == 0 else "test"
        q("keyword", kw, [{"file": "handbook.md", "phrases": [value]}], split=split, fact=key)
        q("typo", typo, [{"file": "handbook.md", "phrases": [value]}], split=split, fact=key)
