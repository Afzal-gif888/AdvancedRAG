def build_scan_pdf() -> bytes:
    from PIL import Image, ImageDraw, ImageFont

    pages = []
    font = ImageFont.load_default(size=34)
    for lines in SCAN_LINES:
        img = Image.new("RGB", (1400, 60 + len(lines) * 60 + 100), "white")
        d = ImageDraw.Draw(img)
        for k, line in enumerate(lines):
            d.text((50, 40 + k * 60), line, fill="black", font=font)
        pages.append(img)
    buf = io.BytesIO()
    pages[0].save(buf, format="PDF", save_all=True, append_images=pages[1:], resolution=150)
    return buf.getvalue()


def _table_pdf(pages, header, bordered, col_x, right):
    """pages: list of row lists; each page gets a title line and the table (header repeated on every page)."""
    from reportlab.pdfgen import canvas

    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=(612, 792))
    for title, rows in pages:
        c.setFont("Helvetica", 11)
        c.drawString(72, 750, title)
        top, row_h = 720, 20
        c.setFont("Helvetica", 10)
        for r, row in enumerate([header] + list(rows)):
            for x, cell in zip(col_x, row):
                c.drawString(x + 4, top - (r + 1) * row_h + 6, cell)
        if bordered:
            n = len(rows) + 1
            for r in range(n + 1):
                c.line(col_x[0], top - r * row_h, right, top - r * row_h)
            for x in list(col_x) + [right]:
                c.line(x, top, x, top - n * row_h)
        c.showPage()
    c.save()
    return buf.getvalue()


