"""Generate constraints/<service>.txt: exact versions for every package a service image installs.

    python scripts/make_constraints.py            # needs network (pip's resolver reads the package index)

Why: the requirements files are ranges (`fastapi>=0.115`), so two builds a month apart install different code, and an
audit of one environment says nothing about the next image. A constraints file does not add or remove packages; it fixes
the version of each one the resolver would pick anyway. Dockerfiles install with `-c constraints/<service>.txt`.

How: for each service pip resolves its requirements for the TARGET platform of the images (CPython 3.12, Linux x86-64,
wheels only) without installing anything. Each resolved package is then pinned to the version installed in THIS
environment when there is one, because that is the version the test suites ran against and `pip-audit` checked;
packages that exist only on Linux (e.g. uvloop) or that this environment does not have get the version the resolver chose and
are listed in a comment as "not exercised by the local test run". Finally pip re-resolves with the constraints applied to prove
they are mutually consistent for the target platform. Run it again to move to newer versions on purpose, then re-run the tests
and `pip-audit`.
"""
import json
import subprocess
import sys
import tempfile
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "constraints"
TARGET = ["--python-version", "3.12", "--implementation", "cp", "--abi", "cp312", "--only-binary=:all:",
          "--platform", "manylinux2014_x86_64", "--platform", "manylinux_2_17_x86_64", "--platform", "manylinux_2_28_x86_64", "--platform", "linux_x86_64"]
# Each service is a list of install steps; a step marked no_deps is resolved without its dependencies, exactly as its Dockerfile
# installs it (see rag-core/requirements.txt for why fastembed and rapidocr are installed that way).
SERVICES = {
    "backend": [(["-r", "backend/requirements.txt"], False)],
    "rag-core": [(["-r", "rag-core/requirements.txt"], False), (["-r", "rag-core/requirements-fastembed.txt"], True),
                 (["rapidocr-onnxruntime"], True)],
    "agent-core": [(["-r", "agent-core/requirements.txt"], False)],
    "llm": [(["-r", "llm/requirements.txt"], False)],
}


def norm(name: str) -> str:
    return name.lower().replace("_", "-").replace(".", "-")


def resolve(args, constraints=None) -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "r.json"
        cmd = [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet", "--report", str(report), "--target", str(Path(tmp) / "t"), *TARGET, *args]
        if constraints:
            cmd += ["-c", str(constraints)]
        done = subprocess.run(cmd, capture_output=True, text=True)
        if done.returncode != 0:
            raise SystemExit(f"pip could not resolve {args}:\n{done.stderr[-1500:]}")
        return {norm(i["metadata"]["name"]): i["metadata"]["version"] for i in json.loads(report.read_text(encoding="utf8"))["install"]}


def installed() -> dict:
    return {norm(d.metadata["Name"]): d.version for d in metadata.distributions() if d.metadata["Name"]}


def main() -> int:
    OUT.mkdir(exist_ok=True)
    here = installed()
    for service, steps in SERVICES.items():
        # the shared package is installed from the repository, not from an index
        def run(constraints=None):
            out = {}
            for args, no_deps in steps:
                args = [str(ROOT / a) if a.endswith(".txt") else a for a in args]
                out.update(resolve((["--no-deps"] if no_deps else []) + args, constraints))
            out.pop("advancerag-common", None)
            return out

        resolved = run()
        pins, untested = {}, []
        for name, version in sorted(resolved.items()):
            if name in here:
                pins[name] = here[name]
            else:
                pins[name] = version
                untested.append(name)
        tmp = OUT / f".{service}.candidate"
        tmp.write_text("\n".join(f"{n}=={v}" for n, v in pins.items()) + "\n", encoding="utf8")
        run(constraints=tmp)  # raises if the pins cannot be satisfied together for the target platform
        tmp.unlink()
        lines = [f"# Exact versions for the {service} image (Python 3.12, Linux x86-64). Generated by scripts/make_constraints.py; do not edit by hand.",
                 "# Versions equal to the local test environment are the ones the test suites ran against and pip-audit checked.",
                 f"# Not exercised by the local (Windows, Python {sys.version_info.major}.{sys.version_info.minor}) run, pinned to the resolver's choice: {', '.join(untested) or 'none'}"]
        lines += [f"{n}=={v}" for n, v in pins.items()]
        (OUT / f"{service}.txt").write_text("\n".join(lines) + "\n", encoding="utf8")
        print(f"{service}: {len(pins)} packages pinned ({len(untested)} not exercised locally)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
