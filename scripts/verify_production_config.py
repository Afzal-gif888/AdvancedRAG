"""Offline check of the production configuration declared in render.yaml. It deploys nothing, contacts nothing and
reads no secrets (no .env file is opened).

For every service it builds the environment the Blueprint would give the container, replaces every value that is
entered in the dashboard or generated by Render (`sync: false`, `generateValue`, `fromService`) with a syntactically
valid DUMMY, then loads that service's real Settings class with ENVIRONMENT=production and runs its safety checks.

It therefore proves: the declared (non-secret) values are accepted by the code's production fail-fast rules, every
declared key is a real setting (a typo would be silently ignored by the services), and it lists risky choices.
It does NOT prove: that the dashboard values are set or correct, that the services can reach each other, or that
anything is deployed. Exit status 1 if a service fails to load or a key is unknown.

    python scripts/verify_production_config.py [path/to/render.yaml] [--overlay overlay.yaml]

An overlay (see infrastructure/durable-storage/) lists `set:` keys, `remove:` keys and `dashboard_secrets:` for one service;
it is applied on top of the Blueprint so a proposed change can be validated before anyone makes it.
"""
import json
import os
import re
import secrets
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SERVICES = {
    "advancerag-backend": ("backend", "app.core.config"),
    "advancerag-rag-core": ("rag-core", "rag_core.config"),
    "advancerag-agent-core": ("agent-core", "agent_core.config"),
    "advancerag-llm": ("llm", "llm_service.config"),
}

PROBE = r'''
import importlib, json, os, sys
prod = json.loads(os.environ.pop("_PROD_ENV"))
os.environ.update(prod)
os.environ["ENVIRONMENT"] = "development"  # only to import the module and list its fields
mod = importlib.import_module(sys.argv[1])
fields = sorted(f.upper() for f in mod.Settings.model_fields)
os.environ.clear(); os.environ.update(prod)
try:
    s = mod.Settings()
    s = s.check_safety() if hasattr(s, "check_safety") else s
    out = {"ok": True, "fields": fields, "values": {k: str(getattr(s, k, None)) for k in ("STORAGE_BACKEND", "OCR_ENABLED", "CHUNKING_STRATEGY", "EMBEDDING_MODEL", "PINECONE_INDEX", "RATE_LIMIT_BACKEND") if hasattr(s, k)}}
except Exception as exc:  # pydantic ValidationError or the safety check's own error
    out = {"ok": False, "fields": fields, "error": str(exc)[:1500]}
print("@@" + json.dumps(out))
'''


def dummy(key: str, spec: dict) -> str:
    k = key.upper()
    if "DATABASE_URL" in k:
        return "postgresql+asyncpg://user:pass@db.example.invalid/dbname?sslmode=require"
    if k == "REDIS_URL":
        return "redis://cache.example.invalid:6379"
    if k.endswith("_URL") or "BASE_URL" in k:
        return "https://service.example.invalid" + ("/v1" if k.startswith("FREELLMAPI") else "")
    return secrets.token_urlsafe(48)  # tokens, keys, secrets: random, never printed


def main() -> int:
    args = sys.argv[1:]
    overlay = None
    if "--overlay" in args:
        i = args.index("--overlay")
        overlay = yaml.safe_load(Path(args[i + 1]).read_text(encoding="utf8"))
        del args[i : i + 2]
    blueprint = Path(args[0]) if args else ROOT / "render.yaml"
    bp = yaml.safe_load(blueprint.read_text(encoding="utf8"))
    groups = {g["name"]: g.get("envVars", []) for g in bp.get("envVarGroups", [])}
    failed = False
    warnings = []
    for svc in bp["services"]:
        if svc["name"] not in SERVICES:
            continue
        folder, module = SERVICES[svc["name"]]
        env, declared, placeholders = {}, [], []
        entries = []
        for e in svc.get("envVars", []):
            entries += groups.get(e["fromGroup"], []) if "fromGroup" in e else [e]
        if overlay and overlay.get("service") == svc["name"]:
            gone = set(overlay.get("remove", []))
            entries = [e for e in entries if e["key"] not in gone and e["key"] not in overlay.get("set", {})]
            entries += [{"key": k, "value": v} for k, v in overlay.get("set", {}).items()]
            entries += [{"key": k, "sync": False} for k in overlay.get("dashboard_secrets", [])]
            print(f"       (overlay applied to {svc['name']}: set {sorted(overlay.get('set', {}))}, removed {sorted(gone)})")
        for e in entries:
            key = e["key"]
            declared.append(key)
            if "value" in e:
                env[key] = str(e["value"])
            else:
                env[key] = dummy(key, e)
                placeholders.append(key)
        run_env = {"PATH": os.environ.get("PATH", ""), "SYSTEMROOT": os.environ.get("SYSTEMROOT", ""), "ADVANCERAG_ENV_FILE": "none",
                   "PYTHONPATH": os.pathsep.join([str(ROOT / "shared"), str(ROOT / folder)]), "_PROD_ENV": json.dumps(dict(env, ADVANCERAG_ENV_FILE="none"))}
        proc = subprocess.run([sys.executable, "-c", PROBE, module], cwd=ROOT / folder, env=run_env, capture_output=True, text=True, timeout=120)
        line = next((ln for ln in proc.stdout.splitlines() if ln.startswith("@@")), None)
        if not line:
            print(f"[FAIL] {svc['name']}: could not run the probe: {proc.stderr[-400:]}")
            failed = True
            continue
        res = json.loads(line[2:])
        unknown = sorted(k for k in declared if k.upper() not in res["fields"] and k not in ("ENVIRONMENT", "MALLOC_ARENA_MAX"))
        status = "OK" if res["ok"] else "FAIL"
        print(f"[{status}] {svc['name']}: {len(declared)} declared keys, {len(placeholders)} replaced by dummies")
        if not res["ok"]:
            failed = True
            print("       " + re.sub(r"\s+", " ", res["error"])[:600])
        if unknown:
            failed = True
            print(f"       keys that are not settings of this service (ignored at runtime): {unknown}")
        v = res.get("values", {})
        if v.get("STORAGE_BACKEND") == "local":
            warnings.append(f"{svc['name']}: STORAGE_BACKEND=local on an ephemeral disk: uploaded files are lost on restart (documents then fail with FILE_MISSING). Use db or s3.")
        if svc["name"] == "advancerag-rag-core":
            warnings.append(f"rag-core effective: OCR_ENABLED={v.get('OCR_ENABLED')}, CHUNKING_STRATEGY={v.get('CHUNKING_STRATEGY')}, EMBEDDING_MODEL={v.get('EMBEDDING_MODEL')}, PINECONE_INDEX={v.get('PINECONE_INDEX')} (informational)")
    if warnings:
        print("\nNotes:")
        for w in warnings:
            print("  - " + w)
    print("\nThis check used dummy values for every dashboard/generated setting; it says nothing about the real values or the live services.")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
